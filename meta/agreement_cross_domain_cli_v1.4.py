#!/usr/bin/env python3
"""
agreement_cross_domain_cli_v1.4.py
==================================

Builds {tab:cross_domain} (RQ4) from TWO independently classified databases:

    S1 = primary domain, iteratively engineered prompts   (e.g. PCB AOI)
    S2 = secondary domain, rapidly prototyped prompts     (e.g. SLR automation)

Usage
-----
    python meta/agreement_cross_domain_cli_v1.4.py \
        --db-s1  data/researchparsa_pcb.db   --config-s1 configs/pcb_aoi.yaml \
        --db-s2  data/researchparsa_slr.db   --config-s2 configs/slr_auto.yaml \
        -o cross_domain

Outputs
-------
    cross_domain_tables.tex   ->  \\begin{table*} ... \\label{tab:cross_domain}
    cross_domain_macros.tex   ->  \\placeholderDTwo*, \\placeholderOnTopic*, ...

Both files are \\input-able from the manuscript (see the paper wiring notes).
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from meta import cross_domain_core as xdc


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Cross-domain (S1 vs S2) agreement comparison for ResearchParsa",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    ap.add_argument("--db-s1", "--db1", required=True,
                    help="SQLite DB for the primary domain (engineered prompts)")
    ap.add_argument("--db-s2", "--db2", required=True,
                    help="SQLite DB for the secondary domain (rapid prompts)")
    ap.add_argument("--config-s1", default=None, help="domain_config.yaml for S1")
    ap.add_argument("--config-s2", default=None, help="domain_config.yaml for S2")
    ap.add_argument("--loader", default=None,
                    help="Dotted path of the agreement_core corpus loader if "
                         "auto-detection fails (e.g. agreement_core.load_papers)")
    ap.add_argument("--col-s1", default=r"S1 -- PCB AOI (engineered)",
                    help="Column header for S1")
    ap.add_argument("--col-s2", default=r"S2 -- SLR automation (rapid)",
                    help="Column header for S2")
    ap.add_argument("-o", "--output", default="cross_domain",
                    help="Output path prefix (default: cross_domain)")
    ap.add_argument("--no-contradiction-breakdown", action="store_true",
                    help="Omit the YYN/YNN/YNU sub-rows")
    ap.add_argument("--emit-stat-aliases", action="store_true",
                    help="Also emit \\StatDTwo* aliases alongside \\placeholder*")
    ap.add_argument("--no-latex", action="store_true",
                    help="Print the comparison, do not write .tex files")
    ap.add_argument("-q", "--quiet", action="store_true")
    args = ap.parse_args(argv)

    for p in (args.db_s1, args.db_s2):
        if not Path(p).exists():
            print(f"Error: database not found: {p}", file=sys.stderr)
            return 1

    if not args.quiet:
        print("ResearchParsa | Cross-Domain Agreement Comparison (RQ4)\n")

    try:
        res_s1, info_s1 = xdc.run_domain_analysis(
            args.db_s1, args.config_s1, loader=args.loader, quiet=args.quiet)
        res_s2, info_s2 = xdc.run_domain_analysis(
            args.db_s2, args.config_s2, loader=args.loader, quiet=args.quiet)
    except AttributeError as e:
        print(f"Error: {e}", file=sys.stderr)
        return 1

    xdom = xdc.summarize_cross_domain(
        res_s1, res_s2,
        label_map_s1=info_s1["label_map"], label_map_s2=info_s2["label_map"],
        categories_s1=info_s1["categories"], categories_s2=info_s2["categories"],
    )

    if not args.quiet:
        _print_comparison(xdom, args.col_s1, args.col_s2)

    if args.no_latex:
        return 0

    prefix = args.output
    table_path = f"{prefix}_tables.tex"
    macros_path = f"{prefix}_macros.tex"
    xdc.write_cross_domain_outputs(
        xdom, table_path, macros_path,
        col_s1=args.col_s1, col_s2=args.col_s2,
        emit_stat_aliases=args.emit_stat_aliases,
        quiet=args.quiet,
    )

    # Patch the table if the breakdown was disabled
    if args.no_contradiction_breakdown:
        tbl = xdc.build_cross_domain_table(
            xdom, col_s1=args.col_s1, col_s2=args.col_s2,
            contradiction_breakdown=False)
        with open(table_path, "w", encoding="utf-8") as f:
            f.write("% Cross-Domain Agreement Comparison (tab:cross_domain)\n")
            f.write("% Generated by cross_domain_core.py -- DO NOT EDIT MANUALLY\n\n")
            f.write(tbl)

    if not args.quiet:
        print("\nAnalysis complete.")
    return 0


def _print_comparison(xdom: dict, c1: str, c2: str) -> None:
    s1, s2 = xdom["s1"], xdom["s2"]
    w = max(len(c1), len(c2), 34)
    print("=" * 90)
    print(f"{'Metric':<34}{c1:>{w}}{c2:>{w}}")
    print("-" * 90)
    rows = [
        ("Corpus papers",        f"{s1['total_papers']:,}",      f"{s2['total_papers']:,}"),
        ("Taxonomy fields",      f"{s1['n_fields']}",            f"{s2['n_fields']}"),
        ("On-topic papers",      f"{s1['on_topic_papers']:,}",   f"{s2['on_topic_papers']:,}"),
        ("On-topic decisions",   f"{s1['on_topic_obs']:,}",      f"{s2['on_topic_obs']:,}"),
    ]
    for key, lbl in (("perfect", "Perfect"), ("uncertain", "Uncertain"),
                     ("biased_certain", "  Biased Certain"),
                     ("biased_uncertain", "  Biased Uncertain"),
                     ("contradiction", "Contradictions")):
        a, b = s1["metrics"][key], s2["metrics"][key]
        rows.append((lbl, f"{a['pct']:.2f}% ({a['count']:,})",
                          f"{b['pct']:.2f}% ({b['count']:,})"))
    mc1, mc2 = s1.get("most_contra"), s2.get("most_contra")
    rows.append(("Most contradictory",
                 f"{mc1['field_label']} {mc1['pct']:.2f}%" if mc1 else "--",
                 f"{mc2['field_label']} {mc2['pct']:.2f}%" if mc2 else "--"))
    for a, b, c in rows:
        print(f"{a:<34}{b:>{w}}{c:>{w}}")
    print("-" * 90)
    print(f"Perfect-agreement delta : {xdc.fmt_trim(xdom['agreement_delta'])} pp")
    print(f"Contradiction ceiling   : {xdc.fmt_trim(xdom['contradiction_ceiling'])}%")
    print("=" * 90 + "\n")


if __name__ == "__main__":
    sys.exit(main())